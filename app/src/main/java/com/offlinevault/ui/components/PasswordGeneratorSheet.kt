@OptIn(ExperimentalMaterial3Api::class)
@Composable
fun PasswordGeneratorSheet(
    onDismiss: () -> Unit,
    onUse: (String) -> Unit
) {
    val sheetState = rememberModalBottomSheetState(skipPartiallyExpanded = true)
    val context = LocalContext.current

    var options by remember { mutableStateOf(GeneratorOptions()) }
    var generated by remember { mutableStateOf(PasswordGenerator.generate(options)) }
    var copied by remember { mutableStateOf(false) }
    var copyFailed by remember { mutableStateOf(false) }
    var phraseMode by remember { mutableStateOf(false) }
    var phraseWords by remember { mutableStateOf(6) }
    var phraseSeparator by remember { mutableStateOf("-") }

    LaunchedEffect(copied) {
        if (copied) { delay(1800); copied = false }
    }

    fun regenerate(newOptions: GeneratorOptions = options) {
        var safe = newOptions
        if (!safe.useUpper && !safe.useLower && !safe.useDigits && !safe.useSymbols) {
            safe = safe.copy(useLower = true)
        }
        options = safe
        generated = if (phraseMode) PasswordGenerator.generatePassphrase(phraseWords, phraseSeparator)
            else PasswordGenerator.generate(safe)
        copied = false
        copyFailed = false
    }

    val strength = PasswordStrengthChecker.evaluate(generated)
    val enabledClassCount = listOf(
        options.useUpper,
        options.useLower,
        options.useDigits,
        options.useSymbols
    ).count { it }

    ModalBottomSheet(
        onDismissRequest = onDismiss,
        sheetState = sheetState,
        containerColor = MaterialTheme.colorScheme.surface
    ) {
        Column(Modifier.fillMaxWidth().wrapContentWidth().widthIn(max = 640.dp)
            .verticalScroll(rememberScrollState()).navigationBarsPadding()
            .padding(horizontal = 20.dp).padding(bottom = 24.dp)) {
            Text("密码生成器", style = MaterialTheme.typography.titleLarge, fontWeight = FontWeight.SemiBold)
            Spacer(Modifier.height(4.dp))
            Text("在本机随机生成，不会发送到任何地方。", style = MaterialTheme.typography.bodyMedium,
                color = MaterialTheme.colorScheme.onSurfaceVariant)
            Spacer(Modifier.height(16.dp))
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                listOf("随机密码" to false, "口令短语" to true).forEach { (title, phrase) ->
                    FilterChip(selected = phraseMode == phrase, onClick = { phraseMode = phrase; regenerate() }, label = { Text(title) })
                }
            }

            SectionCard {
                Column {
                    Row(
                        Modifier.fillMaxWidth(),
                        verticalAlignment = Alignment.CenterVertically,
                        horizontalArrangement = Arrangement.SpaceBetween
                    ) {
                        Text(
                            generated,
                            style = MaterialTheme.typography.titleMedium,
                            fontFamily = FontFamily.Monospace,
                            modifier = Modifier.weight(1f)
                        )
                        IconButton(onClick = { regenerate() }) {
                            Icon(Icons.Filled.Refresh, contentDescription = "重新生成", tint = MaterialTheme.colorScheme.primary)
                        }
                        IconButton(onClick = {
                            copied = ClipboardHelper.copySensitive(context, "生成的密码", generated, 10)
                            copyFailed = !copied
                        }) {
                            Icon(if (copied) Icons.Filled.Check else Icons.Filled.ContentCopy,
                                contentDescription = if (copied) "已复制，10 秒后清除" else "复制密码",
                                tint = MaterialTheme.colorScheme.primary)
                        }
                    }
                    Spacer(Modifier.height(10.dp))
                    if (phraseMode) {
                        Text("约 ${PasswordGenerator.passphraseEntropyBits(phraseWords).toInt()} 位熵：假设每个词独立、均匀随机抽取；分隔符不计入熵。",
                            style = MaterialTheme.typography.bodySmall)
                        Text("这是登录口令，不是恢复助记词。", style = MaterialTheme.typography.bodySmall)
                    } else StrengthMeter(score = strength.score, level = strength.level)
                }
            }

            Spacer(Modifier.height(16.dp))

            if (phraseMode) {
                Text("单词数量", style = MaterialTheme.typography.titleSmall)
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    listOf(6, 8, 10).forEach { count ->
                        FilterChip(selected = phraseWords == count, onClick = { phraseWords = count; regenerate() }, label = { Text("$count 词") })
                    }
                }
                Text("分隔符", style = MaterialTheme.typography.titleSmall)
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    listOf("-", " ", ".").forEach { separator ->
                        FilterChip(selected = phraseSeparator == separator, onClick = { phraseSeparator = separator; regenerate() },
                            label = { Text(if (separator == " ") "空格" else separator) })
                    }
                }
                Text("词库随应用内置。8 个词预设提供更多随机性。", style = MaterialTheme.typography.bodySmall)
            } else {
            Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
                Text("密码长度", style = MaterialTheme.typography.titleSmall)
                Text("${options.length} 位", style = MaterialTheme.typography.titleSmall, fontFamily = FontFamily.Monospace)
            }
            Slider(
                value = options.length.toFloat(),
                onValueChange = { value ->
                    val length = value.roundToInt()
                    if (length != options.length) regenerate(options.copy(length = length))
                },
                valueRange = PasswordGenerator.MIN_LENGTH.toFloat()..PasswordGenerator.MAX_LENGTH.toFloat(),
                steps = PasswordGenerator.MAX_LENGTH - PasswordGenerator.MIN_LENGTH - 1
            )
            Text(when {
                copyFailed -> "复制失败，请重试。"
                copied -> "已复制，剪贴板将在 10 秒后清除。"
                else -> "至少保留一种字符类型。"
            }, style = MaterialTheme.typography.bodySmall,
                color = if (copyFailed) MaterialTheme.colorScheme.error else MaterialTheme.colorScheme.onSurfaceVariant)
            Spacer(Modifier.height(12.dp))

            ToggleRow("大写字母（A-Z）", options.useUpper, enabled = !options.useUpper || enabledClassCount > 1) {
                regenerate(options.copy(useUpper = it))
            }
            ToggleRow("小写字母（a-z）", options.useLower, enabled = !options.useLower || enabledClassCount > 1) {
                regenerate(options.copy(useLower = it))
            }
            ToggleRow("数字（0-9）", options.useDigits, enabled = !options.useDigits || enabledClassCount > 1) {
                regenerate(options.copy(useDigits = it))
            }
            ToggleRow("符号（!@#）", options.useSymbols, enabled = !options.useSymbols || enabledClassCount > 1) {
                regenerate(options.copy(useSymbols = it))
            }
            if (enabledClassCount == 1) {
                Text(
                    "至少保留一种字符类型",
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant
                )
            }
            }
            if (phraseMode && (copied || copyFailed)) Text(if (copied) "已复制，10 秒后清除" else "复制失败，请重试")

            Spacer(Modifier.height(16.dp))
            PrimaryButton(
                text = "使用此密码",
                onClick = { onUse(generated) },
                modifier = Modifier.fillMaxWidth()
            )
        }
    }
}

@Composable
private fun ToggleRow(label: String, checked: Boolean, enabled: Boolean, onChange: (Boolean) -> Unit) {
    Row(
        Modifier.fillMaxWidth().heightIn(min = 56.dp),
        verticalAlignment = Alignment.CenterVertically,
        horizontalArrangement = Arrangement.SpaceBetween
    ) {
        Text(label, style = MaterialTheme.typography.bodyLarge, modifier = Modifier.weight(1f).padding(end = 12.dp))
        Switch(checked = checked, onCheckedChange = onChange, enabled = enabled)
    }
}
